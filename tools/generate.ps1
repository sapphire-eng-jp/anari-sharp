# ANARISharp interop binding generator
#
# Regenerates src/ANARISharp/Interop from the ANARI SDK headers using
# ClangSharpPInvokeGenerator (dotnet tool install -g ClangSharpPInvokeGenerator).
#
#   1. anari.h        -> ANARI.cs + typed handle structs (C++ mode)
#   2. anari_enums.h  -> ANARIConstants.cs (raw macro constants, C mode)
#   3. anari_enums.h  -> ANARIEnums.cs (C# enums synthesized from the #defines)

param(
    [string]$ANARIRoot = 'D:\anari\next_release',
    [string]$RepoRoot = (Split-Path $PSScriptRoot -Parent)
)

$ErrorActionPreference = 'Stop'

$interopDir = Join-Path $RepoRoot 'src\ANARISharp\Interop'
$includeDir = Join-Path $ANARIRoot 'include'
$anariHeader = Join-Path $includeDir 'anari\anari.h'
$enumsHeader = Join-Path $includeDir 'anari\frontend\anari_enums.h'

if (-not (Test-Path $anariHeader)) { throw "anari.h not found under '$ANARIRoot'" }
New-Item -ItemType Directory -Force $interopDir | Out-Null

# --- 1) Core C API (parsed as C++ so the anari::api handle structs become typed pointers) ---
ClangSharpPInvokeGenerator `
    --file $anariHeader `
    --include-directory $includeDir `
    --namespace ANARISharp.Interop `
    --method-class-name ANARI `
    --library-path anari `
    --output $interopDir `
    --config file=multi `
    --generate macro-bindings

$anariCs = Join-Path $interopDir 'ANARI.cs'
if (-not (Test-Path $anariCs)) { throw 'ClangSharpPInvokeGenerator produced no ANARI.cs' }

# ClangSharp emits `sbyte* type = "default"u8` for ANARI_DEFAULT_VAL, which is not valid C#.
(Get-Content $anariCs -Raw) -replace ' = "default"u8', '' | Set-Content $anariCs -Encoding utf8

# --- 2) Raw macro constants (parsed as C so ANARI_DATA_TYPE_DEFINE(v) expands to plain ints) ---
ClangSharpPInvokeGenerator `
    --file $enumsHeader `
    --language c --std c11 `
    --include-directory $includeDir `
    --namespace ANARISharp.Interop `
    --method-class-name ANARIConstants `
    --library-path anari `
    --output (Join-Path $interopDir 'ANARIConstants.cs') `
    --generate macro-bindings

# --- 3) Synthesize C# enums from the #define blocks in anari_enums.h ---
$dataTypeMembers = New-Object System.Collections.ArrayList
$scalarEnums = [ordered]@{}
$current = $null

foreach ($line in (Get-Content $enumsHeader)) {
    if ($line -match '^#define (ANARI_\w+) ANARI_DATA_TYPE_DEFINE\((\d+)\)') {
        [void]$dataTypeMembers.Add(@($Matches[1], $Matches[2]))
        continue
    }
    if ($line -match '^typedef (int|unsigned) (ANARI\w+);') {
        if ($Matches[2] -eq 'ANARIDataType') { $current = $null; continue }
        $current = $Matches[2]
        $underlying = 'int'
        if ($Matches[1] -eq 'unsigned') { $underlying = 'uint' }
        $scalarEnums[$current] = @{ Underlying = $underlying; Members = (New-Object System.Collections.ArrayList) }
        continue
    }
    if ($null -ne $current -and $line -match '^#define (\w+) (\d+)') {
        [void]$scalarEnums[$current].Members.Add(@($Matches[1], $Matches[2]))
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('namespace ANARISharp.Interop')
[void]$sb.AppendLine('{')

[void]$sb.AppendLine('    public enum ANARIDataType : int')
[void]$sb.AppendLine('    {')
foreach ($m in $dataTypeMembers) {
    [void]$sb.AppendLine(('        {0} = {1},' -f $m[0], $m[1]))
}
[void]$sb.AppendLine('    }')

foreach ($name in $scalarEnums.Keys) {
    $info = $scalarEnums[$name]
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine(('    public enum {0} : {1}' -f $name, $info.Underlying))
    [void]$sb.AppendLine('    {')
    foreach ($m in $info.Members) {
        [void]$sb.AppendLine(('        {0} = {1},' -f $m[0], $m[1]))
    }
    [void]$sb.AppendLine('    }')
}

[void]$sb.AppendLine('}')

Set-Content -Path (Join-Path $interopDir 'ANARIEnums.cs') -Value $sb.ToString() -Encoding utf8

# --- 4) Prepend the license header to every generated file ---
# (NativeTypeNameAttribute.cs is hand-written support code and keeps its own header.)
$header = @(
    '// Copyright 2026 Sapphire ENG. Co., Ltd.',
    '// SPDX-License-Identifier: Apache-2.0',
    '//',
    '// <auto-generated/>',
    '// Generated from the ANARI SDK headers by tools/generate.ps1; do not edit by hand.',
    '// Original headers Copyright The Khronos Group Inc., licensed under Apache-2.0.',
    '',
    ''
) -join "`r`n"

$utf8Bom = New-Object System.Text.UTF8Encoding($true)
Get-ChildItem $interopDir -Filter *.cs |
    Where-Object { $_.Name -ne 'NativeTypeNameAttribute.cs' } |
    ForEach-Object {
        $body = [System.IO.File]::ReadAllText($_.FullName)
        [System.IO.File]::WriteAllText($_.FullName, $header + $body, $utf8Bom)
    }

Write-Host "Interop bindings regenerated into $interopDir"

